#!/usr/bin/env python3
"""Embed curated RNA fixtures as reusable offline JavaScript data (no runtime fetch)."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'js/rna-structures.js'

def render():
    assets = ROOT / 'assets/rna-folding'
    data = {key: json.loads((assets / name).read_text()) for key, name in [
        ('acceptorT', 'tertiary-v4-1ehz.json'),
        ('tetraloopReceptor', 'tertiary-v4-1hr2.json'),
    ]}
    payload = json.dumps(data, ensure_ascii=False, separators=(',', ':'))
    payload = payload.replace('<', '\\u003c').replace('>', '\\u003e').replace('&', '\\u0026')
    return ('/* Curated source coordinates; generated by build/rna-structures.py.\n'
            ' * See assets/rna-folding/SOURCES.md. Camera views are not folding trajectories. */\n'
            'window.RNA_STRUCTURES = ' + payload + ';\n')

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content = render()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text() != content:
            parser.exit(1, 'RNA structures differ from source JSON; rebuild them.\n')
    else:
        OUTPUT.write_text(content)
    print(('Verified' if args.check else 'Built') + ': ' + str(OUTPUT))

if __name__ == '__main__': main()
