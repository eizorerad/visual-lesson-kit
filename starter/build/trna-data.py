#!/usr/bin/env python3
"""Build the portable tRNA record from supplied PDB 1EHZ assets, offline."""

import argparse
import hashlib
import json
import re
import shlex
import sys
from pathlib import Path


def require(ok, message):
    if not ok:
        raise ValueError(message)


def cif_tokens(text):
    """Handle quoted fields and column-one semicolon text in the supplied CIF."""
    lines = iter(text.splitlines())
    for line in lines:
        if line.startswith(';'):
            value = [line[1:]]
            for following in lines:
                if following.startswith(';'):
                    break
                value.append(following)
            else:
                raise ValueError('Unterminated CIF text field')
            yield '\n'.join(value)
        else:
            yield from shlex.split(line, comments=True)


def modification_parents(text):
    tokens = list(cif_tokens(text))
    first = tokens.index('_pdbx_struct_mod_residue.id')
    end = first
    while tokens[end].startswith('_pdbx_struct_mod_residue.'):
        end += 1
    fields = [v.split('.', 1)[1] for v in tokens[first:end]]
    result = {}
    while end < len(tokens) and tokens[end] not in ('loop_', 'stop_') and not tokens[end].startswith('_'):
        row = dict(zip(fields, tokens[end:end + len(fields)]))
        require(len(row) == len(fields), 'Incomplete modified-residue row')
        if row['auth_asym_id'] == 'A':
            result[int(row['auth_seq_id'])] = (row['auth_comp_id'], row['parent_comp_id'])
        end += len(fields)
    require(len(result) == 14, 'Expected the 14 deposited modified residues')
    return result


def build_data(root):
    assets = root / 'assets/rna-folding'
    raw = assets / 'tertiary-1ehz.cif'
    original = json.loads((assets / 'trna-1ehz.json').read_text())
    sha = hashlib.sha256(raw.read_bytes()).hexdigest()
    require(original['mmcif_sha256'] == sha, 'Original tRNA JSON has the wrong mmCIF hash')
    text = raw.read_text()
    match = re.search(r'^_entity_poly\.pdbx_seq_one_letter_code_can\s+([ACGU]+)\s*$', text, re.M)
    require(match is not None, 'Missing canonical ACGU sequence in the supplied mmCIF')
    sequence = match.group(1)
    require(len(sequence) == 76, 'Expected a complete 76-nucleotide tRNA')
    parents = modification_parents(text)
    residues = []
    for r in original['residues']:
        i, component = r['id'], r['component']
        base = parents[i][1] if i in parents else component
        require(i not in parents or parents[i][0] == component, f'Modification mismatch at {i}')
        require(sequence[i - 1] == base, f'Canonical sequence mismatch at {i}')
        residues.append({'id': i, 'component': component, 'base': base, 'xyz': r['c4prime']})
    require([r['id'] for r in residues] == list(range(1, 77)), 'Residue order or completeness changed')
    return {
        'schemaVersion': 1,
        'pdbId': '1EHZ',
        'chain': 'A',
        'model': 1,
        'sourceURL': original['source_url'],
        'entryURL': original['entry_url'],
        'primaryPaperURL': original['primary_paper_url'],
        'sourceHash': sha,
        'method': original['method'],
        'resolutionAngstrom': original['resolution_angstrom'],
        'organism': original['organism'],
        'units': 'angstrom',
        'selectedAtom': "C4'",
        'sequence': sequence,
        'residues': residues,
        'modified': [{'id': r['id'], 'component': r['component'], 'base': r['base']}
                     for r in residues if r['id'] in parents],
        'stemPairs': original['display']['secondary_stem_pairs'],
        'anticodon': [34, 35, 36],
        'cca': [74, 75, 76],
        'basis': original['view_basis_rows'],
        'origin': original['view_origin_angstrom'],
        'representationNotes': [
            'ACGU letters identify parent bases; the 14 deposited modifications retain their component IDs.',
            'One C4-prime position per residue forms a coarse trace, not an atomistic chemical-bond graph.',
            'The 21 conventional stem pairs define the authored cloverleaf, not every tertiary contact.',
            'Transitions between sequence, cloverleaf and deposited 3D coordinates show correspondence, not a physical folding trajectory.',
            'G19-C56 is a Watson-Crick tertiary inter-loop pair, distinct from the 21 conventional stem pairs; G18-PSU55 is noncanonical.',
        ],
    }


def json_text(data):
    return json.dumps(data, ensure_ascii=False, indent=2, allow_nan=False) + '\n'


def javascript_text(data):
    body = json_text(data).rstrip().replace('&', '\\u0026').replace('<', '\\u003c').replace('>', '\\u003e')
    body = body.replace('\u2028', '\\u2028').replace('\u2029', '\\u2029')
    return ('// Generated by build/trna-data.py from supplied PDB 1EHZ assets.\n'
            '// Keep component identity and indices across every representation.\n'
            'window.TRNA_DATA = ' + body + ';\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--project', type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument('--check', action='store_true', help='Fail if stored JSON or embedded JS differs from a fresh build')
    args = parser.parse_args()
    try:
        root = args.project.resolve()
        data = build_data(root)
        outputs = {
            root / 'assets/trna/trna-data.json': json_text(data),
            root / 'js/trna-data.js': javascript_text(data),
        }
        for path, expected in outputs.items():
            if args.check:
                require(path.exists() and path.read_text() == expected, 'Outdated generated data: ' + str(path.relative_to(root)))
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(expected)
        print(('Verified' if args.check else 'Generated') + ' 76 residues, 14 modifications and 21 cloverleaf stem pairs; JSON and JS agree.')
        return 0
    except (OSError, ValueError, KeyError, IndexError) as error:
        print('tRNA data: ' + str(error), file=sys.stderr)
        return 1


if __name__ == '__main__':
    sys.exit(main())
